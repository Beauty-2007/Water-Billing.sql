CALL pr_generate_bill(3,CURRENT_DATE+14);
CALL pr_generate_bill(4,CURRENT_DATE-5);
CALL pr_generate_bill(5,CURRENT_DATE-5);
CALL pr_generate_bill(6,CURRENT_DATE-5);
UPDATE bills SET amount_paid=charge WHERE reading_id=2;

CREATE OR REPLACE VIEW v_overdue_bills AS
SELECT c.full_name,b.due_on,(b.charge-b.amount_paid) AS outstanding_amount
FROM bills b JOIN readings r ON r.reading_id=b.reading_id
JOIN customers c ON c.customer_id=r.customer_id
WHERE b.due_on<CURRENT_DATE AND b.amount_paid<b.charge;
CREATE INDEX idx_bills_due_on ON bills(due_on);
EXPLAIN SELECT * FROM bills WHERE due_on<CURRENT_DATE AND amount_paid<charge;

CREATE OR REPLACE PROCEDURE pr_refresh_receivables()
LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO receivable_snapshot(snapshot_date,total_due)
 SELECT CURRENT_DATE,COALESCE(SUM(charge-amount_paid),0) FROM bills
 ON CONFLICT(snapshot_date) DO UPDATE SET total_due=EXCLUDED.total_due;
END; $$;
CALL pr_refresh_receivables();
CREATE EXTENSION IF NOT EXISTS pg_cron;
SELECT cron.schedule('daily-receivables','30 0 * * *','CALL pr_refresh_receivables()');
