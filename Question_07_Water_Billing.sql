-- ICT371 Question 7: Water Meter Readings and Billing
CREATE TABLE customers(customer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,full_name VARCHAR(120) NOT NULL);
CREATE TABLE readings(
 reading_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id INT NOT NULL REFERENCES customers(customer_id),reading_month DATE NOT NULL,
 previous_reading NUMERIC(12,2) NOT NULL CHECK(previous_reading>=0),
 current_reading NUMERIC(12,2) NOT NULL CHECK(current_reading>=0),
 UNIQUE(customer_id,reading_month),CHECK(EXTRACT(DAY FROM reading_month)=1)
);
CREATE TABLE bills(
 bill_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,reading_id INT NOT NULL UNIQUE REFERENCES readings(reading_id),
 charge NUMERIC(12,2) NOT NULL CHECK(charge>=0),amount_paid NUMERIC(12,2) NOT NULL DEFAULT 0,
 due_on DATE NOT NULL,CHECK(amount_paid>=0 AND amount_paid<=charge)
);
CREATE TABLE receivable_snapshot(snapshot_date DATE PRIMARY KEY,total_due NUMERIC(14,2) NOT NULL);
