CREATE OR REPLACE PROCEDURE pr_generate_bill(p_reading_id INT,p_due_on DATE)
LANGUAGE plpgsql AS $$
DECLARE v_previous NUMERIC(12,2);v_current NUMERIC(12,2);v_charge NUMERIC(12,2);
BEGIN
 SELECT previous_reading,current_reading INTO v_previous,v_current FROM readings WHERE reading_id=p_reading_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown reading'; END IF;
 IF p_due_on IS NULL THEN RAISE EXCEPTION 'Due date required'; END IF;
 IF EXISTS(SELECT 1 FROM bills WHERE reading_id=p_reading_id) THEN RAISE EXCEPTION 'Bill already exists for this reading'; END IF;
 v_charge:=fn_water_charge(v_current-v_previous);
 INSERT INTO bills(reading_id,charge,amount_paid,due_on) VALUES(p_reading_id,v_charge,0,p_due_on);
END; $$;
CALL pr_generate_bill(1,CURRENT_DATE+14);
